package others;

public class User 
{

	public String name;
	public String password;
	public String acces;
	
	public String getName() {
		return name;
	}
	public User setName(String name) {
		this.name = name;
		return this;
	}
	public String getPassword() {
		return password;
	}
	public User setPassword(String password) {
		this.password = password;
		return this;
	}
	public String getAcces() {
		return acces;
	}
	public User setAcces(String acces) {
		this.acces = acces;
		return this;
	}
	
	
}
